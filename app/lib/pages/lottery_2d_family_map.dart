  static Set<int> groupFor(int num) {
    if (num < 0 || num > 99) return {num};
    return byNumber[num] ?? {num};
  }

  static Map<int, Set<int>> _build() {
    final seen = <String>{};
    final result = <int, Set<int>>{};
    for (final list in raw.values) {
      final ints = list.map((s) => int.parse(s)).toSet();
      final sig = (ints.toList()..sort()).join(',');
      if (!seen.add(sig)) continue;
      for (final n in ints) {
        result[n] = ints;
      }
    }
    for (var n = 0; n <= 99; n++) {
      result.putIfAbsent(n, () => {n});
    }
    return result;
